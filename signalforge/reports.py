"""Deterministic, fully attributable reporting. AI output must be reviewed."""
from __future__ import annotations
from datetime import datetime, timezone, timedelta
from .models import ThreatRecord


def recent(records: list[ThreatRecord], days: int = 3, *, now: datetime | None = None) -> list[ThreatRecord]:
    """Published-window filter; a daily brief should not recycle old high-score items."""
    cutoff = ((now or datetime.now(timezone.utc)).astimezone(timezone.utc) - timedelta(days=days)).date()
    retained = []
    for item in records:
        try:
            published = datetime.fromisoformat(item.published_at.replace("Z", "+00:00")).date()
        except ValueError:
            continue
        if published >= cutoff:
            retained.append(item)
    return retained


def pick(records: list[ThreatRecord], max_items: int = 7) -> list[ThreatRecord]:
    return sorted(records, key=lambda r: (r.priority_score, r.published_at), reverse=True)[:max_items]


def digest(records: list[ThreatRecord], max_items: int = 7) -> str:
    selected = pick(records, max_items)
    today = datetime.now(timezone.utc).strftime("%B %d, %Y")
    if not selected:
        return f"# SignalForge 720 Daily Brief — {today} (UTC)\n\nNo records match the current selection.\n"
    demo_note = "\n> **TRAINING DATA ONLY:** Contains simulated records; not a current threat advisory.\n" if any(r.is_demo for r in selected) else ""
    lines = [f"# SignalForge 720 Daily Brief — {today} (UTC)", demo_note,
             "**Scope:** Public source metadata and CISA KEV entries; triage priorities are a transparent heuristic, **not CVSS**."
             " Confirm exposure and remediation with vendor advisories and asset inventory before action.", ""]
    for index, r in enumerate(selected, 1):
        lines += [f"## {index}. {r.title}",
                  f"- **Publisher:** {r.source} | **Published:** {r.published_at} | **Priority:** {r.priority} ({r.priority_score}/100)",
                  f"- **CVE:** {r.cve or 'Not specified'} | **CISA KEV:** {'Simulated yes (TRAINING ONLY)' if r.kev and r.is_demo else 'Yes' if r.kev else 'No / not confirmed'} | **EPSS:** {f'{r.epss:.3f}' if r.epss is not None else 'Unavailable'}",
                  f"- **Source excerpt:** {r.summary or 'Not provided.'}",
                  f"- **Why selected:** {r.rationale}",
                  f"- **Analyst next step:** {'Identify affected assets; verify vendor patches/mitigations and hunt for relevant indicators.' if r.kev else 'Validate source claims and check relevance to owned assets.'}",
                  f"- **Source:** {r.url}", ""]
    lines += ["---", "Generated by SignalForge 720. This is decision support, not an authoritative incident assessment."]
    return "\n".join(lines)


def linkedin_template(records: list[ThreatRecord], max_items: int = 3) -> str:
    selected = pick(records, max_items)
    if not selected:
        return "Select at least one verified source record."
    if any(r.is_demo for r in selected):
        prefix = "🧪 SOC Training Exercise (synthetic examples; not breaking news)\n\n"
    else:
        prefix = "🔐 Cybersecurity threat intelligence: what caught my attention\n\n"
    lines = [prefix]
    for index, r in enumerate(selected, 1):
        summary = r.summary.split(". Required action:")[0].strip() or r.title
        lines.append(f"{index}. {r.title}\n{summary[:220]}{'…' if len(summary) > 220 else ''}\nPriority: {r.priority} (analyst heuristic).")
    lines += ["", "My SOC takeaway: prioritize relevance to your environment, verify advisories, and track investigation decisions. CISA KEV is evidence of known exploitation; news headlines alone are not.", "", "Sources:"]
    for r in selected:
        lines.append(r.url)
    lines += ["", "#CyberSecurity #SOCAnalyst #ThreatIntelligence #BlueTeam"]
    return "\n".join(lines)
